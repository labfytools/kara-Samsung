#!/usr/bin/env node
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const html=fs.readFileSync(path.join(__dirname,'../bin/_kara_micro_test.html'),'utf8');
const start=html.indexOf('function correlateTone('),end=html.indexOf('async function runAutomaticCalibration()',start);
assert(start>0 && end>start);
const ctx=vm.createContext({Math,Float32Array,Int16Array,calibrationSamples:[],calibrationCaptureStartSec:null,calibrationCaptureFrames:0});
vm.runInContext(html.slice(start,end),ctx);
const rate=48000,length=rate/4,ref=new Float32Array(length);
for(let i=0;i<length;i++)ref[i]=.12*(.5+.5*Math.sin(2*Math.PI*i/length))*Math.sin(2*Math.PI*1000*i/rate);
const pos=Math.round(rate*.35),rec=new Float32Array(rate*2);
for(let i=0;i<ref.length;i++)rec[pos+i]=ref[i]*.5;
const d=ctx.waveformDiagnostics(rec,ref,rate,350);
assert(d,'Aligned diagnostic exists');
assert(Math.abs(d.levelDeltaDb+6)<=1,JSON.stringify(d));
assert(d.envelopeCorr>=99,JSON.stringify(d));
assert.equal(d.clippedPercent,0);
const wrong=ctx.waveformDiagnostics(rec,ref,rate,700);
assert(wrong.returnDb<d.returnDb-10,'Wrong onset reports weak return');
const silence=ctx.analyzeFirstArrival(new Float32Array(rate*2),ref,rate,100);
assert(!silence.ok,'silence must be rejected');
const weak=ctx.analyzeFirstArrival(rec,ref,rate,100);
assert(weak.diagnostic,'Rejected or accepted result includes diagnostic');
assert(html.includes('if(calibrationMode)return; // NEVER forward live microphone in calibration'));
assert(html.includes('if(!warmup)results.push(result)'));
console.log('PASS: level ratios, waveform envelope, rejection diagnostics, no disk recording, live-mic guard');
